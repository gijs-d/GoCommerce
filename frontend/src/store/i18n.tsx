const savedLang = (typeof window !== 'undefined' && (localStorage.getItem('preferred_lang') as Language)) || 'nl';
const [lang, setLangState] = createSignal<Language>(savedLang);

export function useI18n() {
  const setLanguage = (newLang: Language) => {
    setLangState(newLang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('preferred_lang', newLang);
    }
  };

  const toggleLanguage = () => {
    setLanguage(lang() === 'nl' ? 'en' : 'nl');
  };

  const t = (key: keyof typeof translations['nl']) => {
    return translations[lang()][key] || key;
  };

  return {
    lang,
    setLanguage,
    toggleLanguage,
    t,
  };
}